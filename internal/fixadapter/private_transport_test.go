package fixadapter

import (
	"context"
	"crypto/tls"
	"crypto/x509"
	"io"
	"net"
	"sync/atomic"
	"testing"
	"time"

	"fix-multiplexer/internal/transport"
	"github.com/quickfixgo/quickfix"
)

func TestPrivateBridgeRejectsUnauthenticatedLocalPeer(t *testing.T) {
	settings := quickfix.NewSettings()
	server, err := privateBridgeTLS(settings)
	if err != nil {
		t.Fatal(err)
	}
	l, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	var dials atomic.Int64
	rejected := make(chan struct{}, 1)
	pool := transport.New(1, 1024, func() {
		select {
		case rejected <- struct{}{}:
		default:
		}
	})
	backend, remote := net.Pipe()
	defer backend.Close()
	bridge := transport.NewBridge(tls.NewListener(l, server), pool, "synthetic", func(context.Context) (net.Conn, error) { dials.Add(1); return remote, nil })
	bridge.Start()
	defer bridge.Close()

	// The attacker knows the address and trusts the presented certificate, but
	// does not possess this process's ephemeral client identity.
	ca, err := settings.GlobalSettings().RawSetting("SocketCABytes")
	if err != nil {
		t.Fatal(err)
	}
	roots := x509.NewCertPool()
	if !roots.AppendCertsFromPEM(ca) {
		t.Fatal("invalid synthetic CA")
	}
	attacker := &tls.Config{RootCAs: roots, ServerName: "127.0.0.1", MinVersion: tls.VersionTLS12, MaxVersion: tls.VersionTLS12}
	c, err := tls.DialWithDialer(&net.Dialer{Timeout: 3 * time.Second}, "tcp", bridge.Address(), attacker)
	if err == nil {
		c.Close()
		t.Fatal("unauthenticated local peer accepted")
	}
	select {
	case <-rejected:
	case <-time.After(3 * time.Second):
		t.Fatal("rejection not observed")
	}
	if dials.Load() != 0 {
		t.Fatal("upstream was dialed before authentication")
	}
	// TLS 1.3 can complete the client-side handshake before the server rejects
	// a missing certificate, so also check the first read and server outcome.
	attacker13 := attacker.Clone()
	attacker13.MinVersion, attacker13.MaxVersion = tls.VersionTLS13, tls.VersionTLS13
	c, err = tls.DialWithDialer(&net.Dialer{Timeout: 3 * time.Second}, "tcp", bridge.Address(), attacker13)
	if err == nil {
		if err = c.SetReadDeadline(time.Now().Add(3 * time.Second)); err != nil {
			t.Fatal(err)
		}
		_, err = c.Read(make([]byte, 1))
		c.Close()
		if err == nil {
			t.Fatal("TLS 1.3 peer without certificate accepted")
		}
		if ne, ok := err.(net.Error); ok && ne.Timeout() {
			t.Fatal("TLS 1.3 peer was not rejected")
		}
	}
	select {
	case <-rejected:
	case <-time.After(3 * time.Second):
		t.Fatal("TLS 1.3 rejection not observed")
	}
	if dials.Load() != 0 {
		t.Fatal("TLS 1.3 unauthenticated peer caused upstream dial")
	}

	// A certificate generated by another process must not be trusted either.
	other := quickfix.NewSettings()
	if _, err = privateBridgeTLS(other); err != nil {
		t.Fatal(err)
	}
	otherCert, err := other.GlobalSettings().RawSetting("SocketCertificateBytes")
	if err != nil {
		t.Fatal(err)
	}
	otherKey, err := other.GlobalSettings().RawSetting("SocketPrivateKeyBytes")
	if err != nil {
		t.Fatal(err)
	}
	otherIdentity, err := tls.X509KeyPair(otherCert, otherKey)
	if err != nil {
		t.Fatal(err)
	}
	wrong := attacker.Clone()
	wrong.Certificates = []tls.Certificate{otherIdentity}
	c, err = tls.DialWithDialer(&net.Dialer{Timeout: 3 * time.Second}, "tcp", bridge.Address(), wrong)
	if err == nil {
		c.Close()
		t.Fatal("untrusted local certificate accepted")
	}
	select {
	case <-rejected:
	case <-time.After(3 * time.Second):
		t.Fatal("untrusted certificate rejection not observed")
	}
	if dials.Load() != 0 {
		t.Fatal("untrusted local certificate caused upstream dial")
	}

	cert, err := settings.GlobalSettings().RawSetting("SocketCertificateBytes")
	if err != nil {
		t.Fatal(err)
	}
	key, err := settings.GlobalSettings().RawSetting("SocketPrivateKeyBytes")
	if err != nil {
		t.Fatal(err)
	}
	identity, err := tls.X509KeyPair(cert, key)
	if err != nil {
		t.Fatal(err)
	}
	client := attacker.Clone()
	client.Certificates = []tls.Certificate{identity}
	c, err = tls.DialWithDialer(&net.Dialer{Timeout: 3 * time.Second}, "tcp", bridge.Address(), client)
	if err != nil {
		t.Fatal("authorized peer rejected", err)
	}
	defer c.Close()
	if err = c.SetDeadline(time.Now().Add(3 * time.Second)); err != nil {
		t.Fatal(err)
	}
	go func() { _, _ = io.Copy(backend, backend) }()
	if _, err = c.Write([]byte("ok")); err != nil {
		t.Fatal(err)
	}
	reply := make([]byte, 2)
	if _, err = io.ReadFull(c, reply); err != nil || string(reply) != "ok" {
		t.Fatal("authorized bridge forwarding failed", err)
	}
	if dials.Load() != 1 {
		t.Fatal("unexpected upstream dial count")
	}
}
